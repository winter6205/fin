"""The driver's OCR evidence must be long enough to check a committed quote.

``ocr_text_sample`` is capped at 160 characters on purpose: the harness may
print exactly one JSON line, and a whole page of recognized text does not belong
in it. The cap has a cost, and this file holds the line that draws it. The gold
manifest commits an ``expected_quote`` per page — on a scanned page that quote is
the only evidence that OCR did not drop digits — and the scanned page's numeric
rows sit hundreds of characters into the page. A 160-character window cannot
reach them, so the quote was unverifiable and the shortfall was recorded as
"unverified" rather than as a pass or a failure.

The fix is a sidecar, not a wider line: the run already writes each page bitmap
next to its record, and the full recognized text is persisted beside it with the
name and digest the bitmap already carries. The bounded line keeps its bound, and
a reviewer reading the artefact can check an exact source-backed quote.

The driver is a script that normally runs inside the pinned image, so it is
loaded by path and only its pure functions are called here, as
``test_g4_pipeline_gap_contract`` does. The image is bind-mounted, not baked
(``Dockerfile``: "driver.py is NOT baked"), so this is a harness change with no
rebuild and no effect on the adopted image identity.
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

PROJECT_ROOT = Path(__file__).resolve().parents[2]
DRIVER_PATH = PROJECT_ROOT / "scripts" / "g4_pipeline" / "driver.py"

# The committed sample window, named here so a change to the driver's constant
# cannot silently make this file agree with a different contract.
SAMPLE_CHARS = 160

# A page whose numeric row is far outside any short sample: this is the shape
# that made the gold quote unreachable, not an arbitrary long string.
LONG_OCR_TEXT = (
    "Apple Inc. CONDENSED CONSOLIDATED STATEMENTS OF CASH FLOWS (Unaudited) "
    "Net cash generated by operating activities 14,483 "
    "Net cash used in investing activities (5,428) "
    "Net cash generated by financing activities (11,204) "
    "Cash, cash equivalents and restricted cash, ending balances 28,161"
)


def _driver() -> ModuleType:
    spec = importlib.util.spec_from_file_location("g4_pipeline_driver_ocr", DRIVER_PATH)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


class _Engine:
    lang = "eng"

    def __init__(self, *, text: str | None = None, fail: bool = False) -> None:
        self._text = text if text is not None else LONG_OCR_TEXT
        self._fail = fail
        self.calls: list[dict[str, Any]] = []

    def recognize(self, *, source: Path, page: int) -> str:
        self.calls.append({"source": source, "page": page})
        if self._fail:
            raise RuntimeError("tesseract exited 1")
        return self._text


class _Bitmap:
    """Enough of a PIL image for the driver's own page-bitmap save."""

    def save(self, path: Any, format: str = "PNG") -> None:  # noqa: A002
        Path(path).write_bytes(b"\x89PNG\r\n\x1a\n")


def _run(
    tmp_path: Path,
    *,
    image_dir: Path | None,
    engine: _Engine,
    page_no: int = 3,
) -> dict[str, object]:
    driver = _driver()
    entry: dict[str, object] = {
        "page_no": page_no,
        "ocr_text_file": None,
        "ocr_text_sha256": None,
    }
    failures: list[str] = []
    driver._apply_page_ocr(
        entry, _Bitmap(), page_no, engine, "repo_rule", image_dir, failures
    )
    assert failures == []
    return entry


# ----- the whole recognized text has to survive the short sample -----------


def test_full_ocr_text_is_persisted_beside_the_page_bitmap(tmp_path: Path) -> None:
    """A committed quote past the sample window must be checkable in the artefact.

    The scanned page's ``Total net sales`` row is the manifest's fixture-
    independent check that OCR did not drop digits, and it lies far beyond 160
    characters into the page. If the run persists only the sample, that quote
    can never be verified and the gold expectation is unfalsifiable.
    """
    entry = _run(tmp_path, image_dir=tmp_path, engine=_Engine())

    sidecar = tmp_path / str(entry["ocr_text_file"])
    assert sidecar.is_file()
    assert sidecar.read_text(encoding="utf-8") == LONG_OCR_TEXT
    assert "Net cash generated by operating activities 14,483" in sidecar.read_text(
        encoding="utf-8"
    )


def test_the_persisted_text_is_named_and_digested_in_the_record(tmp_path: Path) -> None:
    """A sidecar nothing points at is not evidence; a named one without a digest
    cannot be tied to the text the count was taken from."""
    driver = _driver()
    entry = _run(tmp_path, image_dir=tmp_path, engine=_Engine())

    name = entry["ocr_text_file"]
    assert name == "page_0003.ocr.txt"
    assert entry["ocr_text_sha256"] == driver.sha256_bytes(tmp_path / name)[1]


def test_the_json_line_keeps_its_bounded_sample(tmp_path: Path) -> None:
    """Widening the sidecar must not widen the line the harness gates on.

    ``run_measured.sh`` fails the run unless stdout carries exactly one JSON
    line, and the cap exists so a full page of text cannot bloat it. The fix
    belongs beside the line, not inside it.
    """
    entry = _run(tmp_path, image_dir=tmp_path, engine=_Engine())

    assert entry["ocr_text_char_count"] == len(LONG_OCR_TEXT)
    assert entry["ocr_text_sample"] == " ".join(LONG_OCR_TEXT.split())[:SAMPLE_CHARS]
    assert len(str(entry["ocr_text_sample"])) == SAMPLE_CHARS


# ----- the sidecar may not manufacture evidence it does not have -----------


def test_a_failed_ocr_pass_writes_no_text_sidecar(tmp_path: Path) -> None:
    """An empty file beside the bitmap would read as "OCR read nothing".

    A failed pass already reports its own code and error and carries no
    character count; an empty sidecar would add a second, quieter claim of a
    successful read that produced no text.
    """
    driver = _driver()
    entry: dict[str, object] = {
        "page_no": 3,
        "ocr_text_file": None,
        "ocr_text_sha256": None,
    }
    failures: list[str] = []

    driver._apply_page_ocr(
        entry, _Bitmap(), 3, _Engine(fail=True), "repo_rule", tmp_path, failures
    )

    assert entry["ocr_used"] is False
    assert entry["ocr_text_file"] is None
    assert entry["ocr_text_sha256"] is None
    assert list(tmp_path.glob("*.ocr.txt")) == []


def test_nothing_kept_means_no_sidecar_and_no_path(tmp_path: Path) -> None:
    """Without ``--write-images`` the run keeps no bitmaps, so it keeps no text.

    A run that persists the full page text while persisting no bitmaps would
    also make the temp-PNG cleanup path the only thing bounding disk, and the
    record would name a file the run is not entitled to have written.
    """
    entry = _run(tmp_path, image_dir=None, engine=_Engine())

    assert entry["ocr_text_char_count"] == len(LONG_OCR_TEXT)
    assert entry["ocr_text_file"] is None
    assert entry["ocr_text_sha256"] is None


def test_a_page_entry_declines_the_text_file_before_ocr_runs() -> None:
    """The keys exist as null on a page that has not been recognized.

    The record distinguishes "not measured" from "measured to be nothing" by
    spelling its keys out, so a reader must not have to infer the difference
    from a missing key.
    """
    driver = _driver()
    rule_calls: list[dict[str, Any]] = []

    def _rule(*, text: str, image_count: int, min_text_chars: int) -> bool:
        rule_calls.append({"text": text})
        return True

    class _Page:
        def get_size(self) -> tuple[float, float]:
            return (612.0, 792.0)

        def get_textpage(self) -> Any:
            class _TextPage:
                def get_text_range(self) -> str:
                    return ""

            return _TextPage()

        def get_objects(self, *, filter: Any = None) -> list[Any]:  # noqa: A002
            return []

    entry = driver._page_structure_entry(_Page(), 1, _rule)

    assert rule_calls == [{"text": ""}]
    assert entry["ocr_text_file"] is None
    assert entry["ocr_text_sha256"] is None


